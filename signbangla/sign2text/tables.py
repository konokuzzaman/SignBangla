def _verb(present, continuous, past, perfect, future):
    """Each argument: the forms for persons 1, 2_informal, 2_formal, 3, separated by '|'."""
    return dict(zip(TENSES, (present, continuous, past, perfect, future)))


def _with(prefix, verb):
    """A compound verb (সাহায্য করা): the same forms with a word in front."""
    return {t: "|".join(f"{prefix} {f}" for f in forms.split("|")) for t, forms in verb.items()}


