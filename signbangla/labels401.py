CLIP_NAME_RE = re.compile(r"^W(?P<word>\d{3})S(?P<signer>\d{2})(?P<view>[FL])_(?P<clip>\d+)(?:\.mp4)?$", re.IGNORECASE)
VIEW_NAMES = {"F": "Front", "L": "Lateral"}


def parse_clip_name(name):
    """'W001S04F_02' or 'W001S04F_02.mp4' -> {'word': 'W1', 'word_number': 1, 'signer': 4, 'view': 'F', 'clip': 2}.
    None if it does not match. 'word' is written like labels.py: W1, not W001."""
    m = CLIP_NAME_RE.match(name)
    if not m:
        return None
    number = int(m["word"])
    return dict(word=f"W{number}", word_number=number, signer=int(m["signer"]), view=m["view"].upper(), clip=int(m["clip"]))


def write_word_list(path, rows=LABELS_401):
    """Save rows as a CSV with the columns number, bangla, english. utf-8-sig so Excel shows Bangla correctly."""
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["number", "bangla", "english"])
        writer.writerows((number, bangla, english) for number, bangla, _, english in rows)
